export function getMansionForCity(cityId: string): LunarMansionItem | undefined {
  const directMatch = LUNAR_MANSIONS_DATA.find(m => m.associatedCityId === cityId);
  if (directMatch) return directMatch;
  const mappedId = CITY_TO_MANSION_MAP[cityId];
  if (mappedId) return LUNAR_MANSIONS_DATA.find(m => m.id === mappedId);
  return undefined;
}
